static uint8_t SSD1315_Buffer[SSD1315_WIDTH * SSD1315_HEIGHT / 8];

static void SSD1315_WriteCommand(I2C_HandleTypeDef *hi2c, uint8_t byte) {
	I2C_Mem_Write_DMA(hi2c, SSD1315_I2C_ADDR, 0x00, 1, &byte, 1, 100);
}

HAL_StatusTypeDef SSD1315_Init(I2C_HandleTypeDef *hi2c) {
	if (hi2c == NULL) {
		return HAL_ERROR;
	}
	HAL_Delay(100);

	if (HAL_I2C_IsDeviceReady(hi2c, SSD1315_I2C_ADDR, 2, 50) != HAL_OK) {
		return HAL_ERROR;
	}

	SSD1315_WriteCommand(hi2c, 0xAE);
	SSD1315_WriteCommand(hi2c, 0xD5);
	SSD1315_WriteCommand(hi2c, 0x80);
	SSD1315_WriteCommand(hi2c, 0xA8);
	SSD1315_WriteCommand(hi2c, SSD1315_HEIGHT - 1);
	SSD1315_WriteCommand(hi2c, 0xD3);
	SSD1315_WriteCommand(hi2c, 0x00);
	SSD1315_WriteCommand(hi2c, 0x40);
	SSD1315_WriteCommand(hi2c, 0x8D);
	SSD1315_WriteCommand(hi2c, 0x14);
	SSD1315_WriteCommand(hi2c, 0x20);
	SSD1315_WriteCommand(hi2c, 0x00);
	SSD1315_WriteCommand(hi2c, 0xA1);
	SSD1315_WriteCommand(hi2c, 0xC8);
	SSD1315_WriteCommand(hi2c, 0xDA);
	SSD1315_WriteCommand(hi2c, 0x12);
	SSD1315_WriteCommand(hi2c, 0x81);
	SSD1315_WriteCommand(hi2c, 0xCF);
	SSD1315_WriteCommand(hi2c, 0xD9);
	SSD1315_WriteCommand(hi2c, 0xF1);
	SSD1315_WriteCommand(hi2c, 0xDB);
	SSD1315_WriteCommand(hi2c, 0x40);
	SSD1315_WriteCommand(hi2c, 0xA4);
	SSD1315_WriteCommand(hi2c, 0xA6);
	SSD1315_WriteCommand(hi2c, 0xAF);

	SSD1315_Clear();
	SSD1315_Line_1("Initializing...");
	SSD1315_UpdateScreen(hi2c);

	return HAL_OK;
}

void SSD1315_Clear(void) {
	memset(SSD1315_Buffer, 0x00, sizeof(SSD1315_Buffer));
}

void SSD1315_UpdateScreen(I2C_HandleTypeDef *hi2c) {
	for (uint8_t i = 0; i < 8; i++) {
		SSD1315_WriteCommand(hi2c, 0xB0 + i);
		SSD1315_WriteCommand(hi2c, 0x00);
		SSD1315_WriteCommand(hi2c, 0x10);

		I2C_Mem_Write_DMA(hi2c, SSD1315_I2C_ADDR, 0x40, 1, &SSD1315_Buffer[SSD1315_WIDTH * i], SSD1315_WIDTH, 100);
	}
}

void SSD1315_DrawPixel(uint8_t x, uint8_t y, uint8_t color) {
	if (x >= SSD1315_WIDTH || y >= SSD1315_HEIGHT) return;

	if (color) {
		SSD1315_Buffer[x + (y / 8) * SSD1315_WIDTH] |= (1 << (y % 8));
	} else {
		SSD1315_Buffer[x + (y / 8) * SSD1315_WIDTH] &= ~(1 << (y % 8));
	}
}

void SSD1315_DrawBorder(int startX, int endX, int startY, int endY, I2C_HandleTypeDef* handle)
{
	for(int i = startY; i < endY; i++)
	{
		SSD1315_DrawPixel(startX, i, 1);
		SSD1315_DrawPixel(endX, i, 1);
	}
	for(int i = startX; i < endX; i++)
	{
		SSD1315_DrawPixel(i, startY, 1);
		SSD1315_DrawPixel(i, endY, 1);
	}
	SSD1315_UpdateScreen(handle);
}

